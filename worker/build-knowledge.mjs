// Builds src/knowledge.js from the site's own content (js/content.js), so the chatbot can only
// ever know what the public website already says. Run: npm run knowledge
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const window = {};
new Function('window', readFileSync(join(root, 'js/content.js'), 'utf8'))(window);
const S = window.SITE;

const STATUS = { shipped: 'Shipped', 'in-progress': 'In progress (still being built)', internal: 'Internal Solera project (not publicly available)', archived: 'Archived' };
const out = [];
const add = (...lines) => out.push(...lines);

add('## PERSON',
  `Name: ${S.person.name}`, `Title: ${S.person.title}`, `Location: ${S.person.location}`, `School: ${S.person.school}`,
  `Email: ${S.person.email}`, `GitHub: ${S.person.github}`, `LinkedIn: ${S.person.linkedin}`,
  'Portfolio website: https://gasthecreator.github.io/portfolio/',
  'The website hero says: "Software Engineer, available for work".', '');

add('## SUMMARY', S.tagline, S.bio, '');
add('## HEADLINE NUMBERS', ...S.stats.map((s) => `- ${s.value}: ${s.label}`), '');
add('## SKILLS', ...S.skills.map((g) => `${g.name}: ${g.items.join(', ')}`), '');

const project = (p, status) => {
  add(`### ${p.name}`, `Status: ${STATUS[status] || status}`);
  add(`One line: ${p.tagline}`, `Technologies: ${(p.tags || p.tech || []).join(', ')}`);
  if (p.metric) add(`Headline result: ${p.metric.value} (${p.metric.label})`);
  add(`Problem: ${p.problem}`, `Approach: ${p.approach}`, `Stack: ${p.stack}`, `Outcome: ${p.outcome}`);
  if (p.links && p.links.length) add(`Links: ${p.links.map((l) => `${l.label} ${l.href}`).join(' | ')}`);
  add('');
};
add('## PROJECTS (featured)');
S.featured.forEach((p) => project(p, p.status || 'shipped'));
add('## PROJECTS (archive)');
S.archive.forEach((p) => project(p, p.status || 'shipped'));

add('## EXPERIENCE');
S.experience.forEach((e) => add(`### ${e.role}, ${e.org} (${e.dates})`, ...e.bullets.map((b) => `- ${b}`), `Technologies: ${e.tags.join(', ')}`, ''));

add('## EDUCATION');
S.education.forEach((e) => add(`${e.degree}, ${e.school} (${e.dates})`, `Achievements: ${e.achievements.join(', ')}`, `Coursework: ${e.coursework}`));
add(`Certifications: ${S.certifications.join(', ')}`, `Programs and affiliations: ${S.programs.join(', ')}`, '');

add('## ENGINEERING NOTES (write-ups on the site, each linked to its source)');
(S.notes || []).forEach((n) => add(`### ${n.title} (${n.project})`, n.body, ''));
const byId = Object.fromEntries([...S.featured, ...S.archive].map((p) => [p.id, p.name]));
add('## WHERE SKILLS HAVE BEEN USED (projects on the site)',
  ...Object.entries(S.skillEvidence || {}).map(([k, v]) => `${k}: ${v.map((id) => byId[id] || id).join(', ')}`),
  `Strongest areas: ${(S.skillsCore || []).join(', ')}`, '');
add('## USING THE WEBSITE',
  '- The résumé can be viewed in a pop-up (eye icon in the navigation, or "View résumé" in the Contact section) or downloaded as a PDF.',
  '- The Education section has a "Request transcript" button that opens an email to Gideon.',
  '- Each featured and archived project has its own detail page with problem, approach, stack and outcome, plus screenshots, terminal captures, charts or architecture diagrams.',
  '- The Skills section lets visitors pick a skill to see which projects used it.',
  '- The site switches between light and dark by the visitor\'s local time of day (light 6am to 6pm), and the toggle overrides that for the session.',
  `- Closing line on the site: ${S.closing}`, '');

const text = out.join('\n');
writeFileSync(join(root, 'worker/src/knowledge.js'), `// GENERATED by build-knowledge.mjs from js/content.js. Do not edit by hand.\nexport const KNOWLEDGE = ${JSON.stringify(text)};\n`);
console.log(`knowledge.js written: ${text.length} chars (~${Math.round(text.length / 4)} tokens)`);
